const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const elements = new Map();
const element = id => {
  if (!elements.has(id)) elements.set(id, {value: '', textContent: '', disabled: false,
    focus() { this.focused = true; }, showModal() { this.open = true; }, close() { this.open = false; }});
  return elements.get(id);
};
let sent;
let fail = false;
const context = vm.createContext({window: {}, document: {getElementById: element, querySelectorAll: () => []},
  fetch: async (path, options) => {
    assert.equal(path, '/api/download/action');
    sent = JSON.parse(options.body);
    return {ok: !fail, json: async () => fail ? {error: 'NAS 離線'} : {success: true, updated: sent.task_ids, skipped: []}};
  }});
vm.runInContext(fs.readFileSync('uav-web/frontend/task-selection.js', 'utf8'), context);
const selection = context.window.createTaskSelection({});
selection.setTasks([{task_id: 'a', status: 'paused'}, {task_id: 'b', status: 'downloading'}, {task_id: 'c', status: 'pending'}]);
selection.toggleAll();
selection.toggle('c', false);
selection.edit();
assert.equal(element('task-edit-count').textContent, 1);
assert.equal(element('task-edit-dialog').open, true);
(async () => {
  await selection.saveEdit({preventDefault() {}});
  assert.equal(sent, undefined, 'No changes must not send a request');
  element('task-edit-storage').value = 'local';
  selection.updateEditStorage();
  assert.equal(element('task-edit-local-fields').hidden, false);
  assert.equal(element('task-edit-dest').required, true);
  assert.equal(element('task-edit-dest').disabled, false);
  element('task-edit-dest').value = '  ';
  await selection.saveEdit({preventDefault() {}});
  assert.equal(sent, undefined, 'An empty local path must not send a request');
  element('task-edit-dest').value = ' /downloads/chosen ';
  fail = true;
  await selection.saveEdit({preventDefault() {}});
  assert.equal(sent.storage, 'local');
  assert.equal(sent.dest, '/downloads/chosen');
  element('task-edit-storage').value = 'settings';
  selection.updateEditStorage();
  assert.equal(element('task-edit-local-fields').hidden, true);
  assert.equal(element('task-edit-dest').required, false);
  assert.equal(element('task-edit-dest').disabled, true);
  element('task-edit-subtitles').value = 'none';
  fail = true;
  await selection.saveEdit({preventDefault() {}});
  assert.equal(element('task-edit-status').textContent, 'NAS 離線');
  assert.equal(selection.has('a'), true);
  fail = false;
  await selection.saveEdit({preventDefault() {}});
  assert.deepEqual(sent.task_ids, ['a']);
  assert.equal(sent.storage, 'settings');
  assert.equal(sent.dest, undefined);
  assert.equal(sent.subtitle_mode, 'none');
  assert.equal(selection.has('a'), false);
  assert.equal(selection.has('b'), true);
  assert.equal(selection.has('c'), false);
  assert.equal(element('task-edit-dialog').open, false);
  for (const mode of ['upload', 'smb', 'direct']) {
    selection.edit('c');
    element('task-edit-storage').value = mode;
    selection.updateEditStorage();
    assert.equal(element('task-edit-local-fields').hidden, mode !== 'upload');
    assert.equal(element('task-edit-nas-fields').hidden, mode === 'direct');
    assert.equal(element('task-edit-direct-fields').hidden, mode !== 'direct');
    element('task-edit-dest').value = '/downloads/staging';
    element('task-edit-host').value = 'nas-two.local';
    element('task-edit-share').value = 'videos';
    element('task-edit-directory').value = 'chosen';
    element('task-edit-username').value = 'user';
    element('task-edit-password').value = 'queue-password';
    element('task-edit-direct-path').value = '/nas/videos';
    await selection.saveEdit({preventDefault() {}});
    assert.deepEqual(sent.task_ids, ['c'], 'Per-item settings do not require selection');
    assert.equal(sent.storage, 'custom');
    assert.equal(sent.nas.mode, mode);
    assert.equal(sent.nas.host, 'nas-two.local');
    assert.equal(sent.nas.password, 'queue-password');
    assert.equal(sent.dest, mode === 'upload' ? '/downloads/staging' : undefined);
    assert.equal(element('task-edit-password').value, '');
  }
  console.log('Batch task settings, partial selection and failure retention: PASS');
})().catch(error => { console.error(error); process.exitCode = 1; });
