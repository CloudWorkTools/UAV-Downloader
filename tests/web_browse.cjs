const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('uav-web/frontend/index.html', 'utf8');
const elements = new Map();
const cards = [];
const element = id => {
  if (!elements.has(id)) elements.set(id, {value: '', innerHTML: '', textContent: '', options: [], get selectedOptions() {return this.options.filter(option => option.value === this.value);}, classList: {add() {}, remove() {}, toggle() {}}, appendChild(child) { if (id === 'video-grid') cards.push(child); if (id === 'category-select') this.options.push(child); }});
  return elements.get(id);
};
const pending = [];
const context = vm.createContext({
  document: {getElementById: element, createElement: () => ({}), querySelectorAll: () => []},
  window: {addEventListener() {}}, alert() {},
  fetch: (path, options) => new Promise(resolve => pending.push({path, options, resolve})),
});
vm.runInContext(fs.readFileSync('uav-web/frontend/video-selection.js', 'utf8'), context);
context.createVideoSelection = context.window.createVideoSelection;
vm.runInContext(fs.readFileSync('uav-web/frontend/task-selection.js', 'utf8'), context);
context.createTaskSelection = context.window.createTaskSelection;
let chooseCategory;
context.window.createCategoryBrowser = (container, onSelect) => {chooseCategory=onSelect;return {render() {}, select() {}};};
vm.runInContext(html.slice(html.indexOf('    let currentSite'), html.lastIndexOf('  </script>')), context);
const respond = (request, body, ok=true) => request.resolve({ok, json: async () => body});
async function run() {
  context.renderVideos([{url: 'https://example.com/video', thumbnail: 'https://example.com/image.jpg'}]);
  assert.match(cards.at(-1).innerHTML, /referrerpolicy="no-referrer"/, 'Preview must not send the application Referer to image CDNs');
  assert.match(cards.at(-1).innerHTML, /<a href="https:\/\/example.com\/video" target="_blank" rel="noopener noreferrer"/);
  assert.match(cards.at(-1).innerHTML, /開啟原頁/);
  context.renderVideos([{url:'https://example.com/watch?v=1&name="quoted"'}]);
  assert.match(cards.at(-1).innerHTML, /href="https:\/\/example.com\/watch\?v=1&amp;name=&quot;quoted&quot;"/);
  context.renderVideos([{url:'javascript:alert(1)'}]);
  assert.ok(!cards.at(-1).innerHTML.includes('<a href='));
  const first = context.selectSite('JableTV');
  const second = context.selectSite('MissAV');
  respond(pending[1], {categories: [{name:'Latest',url:'https://missav.ai/latest'}]});
  await new Promise(setImmediate);
  respond(pending[0], {categories: [{name:'Latest',url:'https://jable.tv/latest'}]});
  await new Promise(setImmediate);
  assert.equal(pending.length, 3, 'Stale category responses must not trigger another browse');
  assert.equal(JSON.parse(pending[2].options.body).url, 'https://missav.ai/latest');
  respond(pending[2], {videos:[]});
  await Promise.all([first,second]);
  const older = context.fetchBrowse();
  const newer = context.fetchBrowse();
  respond(pending[4], {videos:[{url:'new'}]});
  await newer;
  respond(pending[3], {videos:[{url:'old'}]});
  await older;
  assert.match(cards.at(-1).innerHTML, /'new'/, 'Stale lists must not replace the current page');
  const failure = context.fetchBrowse();
  respond(pending[5], {videos:[],blocked:true,error:'站台防護阻擋'});
  await failure;
  assert.match(cards.at(-1).textContent, /站台防護阻擋/, 'Backend failures must remain visible');
  vm.runInContext('currentPage = 5', context);
  chooseCategory({name:'衣著標籤',url:'https://jable.tv/tags/uniform/'});
  const chosen = JSON.parse(pending[6].options.body);
  assert.equal(chosen.url, 'https://jable.tv/tags/uniform/');
  assert.equal(chosen.page, 1);
  assert.equal(element('selected-category-label').textContent, '衣著標籤');
  respond(pending[6], {videos:[]});
  await new Promise(setImmediate);
  vm.runInContext('currentPage = 5', context);
  element('page-indicator').textContent = '第 5 頁';
  element('search-input').value = 'MIMK- 字幕';
  const search = context.executeSearch();
  assert.equal(pending[7].path, '/api/search');
  respond(pending[7], {videos:[{url:'search-page-1'}], warning:'僅比對前 20 頁', has_more:true});
  await search;
  assert.equal(element('search-warning').textContent, '僅比對前 20 頁');
  assert.equal(element('btn-next-page').disabled, false);
  assert.match(html, /aria-describedby="search-hint"/);
  assert.match(html, /多個關鍵字以空格分隔/);
  assert.equal(element('page-indicator').textContent, '第 1 頁');
  assert.equal(element('btn-prev-page').disabled, true);
  element('search-input').value = 'unsent-edit';
  context.changePage(1);
  assert.equal(pending[8].path, '/api/search', 'Search pagination must not fall back to the selected category');
  assert.equal(JSON.parse(pending[8].options.body).query, 'MIMK- 字幕');
  assert.equal(JSON.parse(pending[8].options.body).page, 2);
  respond(pending[8], {videos:[{url:'search-page-2'}], has_more:false});
  await new Promise(setImmediate);
  assert.equal(element('btn-next-page').disabled, true);
  assert.equal(element('search-warning').textContent, '');
  context.changePage(-1);
  assert.equal(pending[9].path, '/api/search');
  assert.equal(JSON.parse(pending[9].options.body).page, 1);
  respond(pending[9], {videos:[{url:'search-page-1'}]});
  await new Promise(setImmediate);
  assert.equal(element('btn-next-page').disabled, false);
  assert.match(cards.at(-1).innerHTML, /'search-page-1'/);
  chooseCategory({name:'分類',url:'https://missav.ai/latest'});
  assert.equal(pending[10].path, '/api/browse', 'Selecting a category exits search mode');
  respond(pending[10], {videos:[]});
  await new Promise(setImmediate);
  for (const site of ['JableTV', 'MissAV', 'SupJav', 'Hanime1']) {
    vm.runInContext(`currentSite = '${site}'`, context);
    element('search-input').value = 'MIMK';
    let index = pending.length;
    const search = context.executeSearch();
    respond(pending[index], {videos:[]});
    await search;
    context.changePage(1);
    const body = JSON.parse(pending[++index].options.body);
    assert.equal(pending[index].path, '/api/search');
    assert.deepEqual(body, {site, query:'MIMK', page:2});
    respond(pending[index], {videos:[]});
    await new Promise(setImmediate);
  }
  let index = pending.length;
  const switching = context.selectSite('MissAV');
  respond(pending[index], {categories:[{name:'Latest',url:'https://missav.ai/latest'}]});
  await new Promise(setImmediate);
  assert.equal(pending[++index].path, '/api/browse', 'Switching sites exits search mode');
  respond(pending[index], {videos:[]});
  await switching;
  vm.runInContext("currentSite='JableTV'; currentSearchQuery='MIMK'; currentPage=1; browseLoading=true", context);
  context.renderBackendActivity({observed_at:1700000000, activities:[{title:'搜尋影片',site:'JableTV',query:'MIMK',page:1,state:'running',elapsed_seconds:12,message:'讀取第 4 頁',parts:{MIMK:'已讀取 4 頁'}}]});
  assert.match(element('browse-loading-message').textContent, /讀取第 4 頁.*12 秒/);
  assert.match(element('backend-work-list').innerHTML, /已讀取 4 頁/);
  context.renderBackendActivity({activities:[{title:'搜尋影片',site:'MissAV',query:'other',page:1,state:'running',elapsed_seconds:1,message:'wrong query'}]});
  assert.ok(!element('browse-loading-message').textContent.includes('wrong query'));
  context.renderBackendActivity({activities:[{title:'<script>',state:'failed',message:'<img onerror=alert(1)>',elapsed_seconds:1}]});
  assert.ok(!element('backend-work-list').innerHTML.includes('<img onerror'));
  assert.match(element('backend-work-list').innerHTML, /&lt;img/);
  assert.ok(html.indexOf('id="backend-activity-panel"') > html.indexOf('</main>'), 'Work activity belongs below the main content');
  assert.match(html, /<details id="backend-activity-panel" class=/);
  assert.ok(!/<details[^>]*id="backend-activity-panel"[^>]*\bopen\b/.test(html), 'Activity starts collapsed');
  assert.match(element('backend-work-list').innerHTML, /backend-work-card/);
  console.log('Search pagination, page reset, category/site reset, preview and request races: PASS');
}
run().catch(e => {console.error(e);process.exitCode=1;});
